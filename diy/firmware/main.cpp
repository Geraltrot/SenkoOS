// DIY repeater application: upstream simple_repeater (MyMesh, UITask) plus
// Wi-Fi and a local web panel. Based on examples/simple_repeater/main.cpp of
// MeshCore v1.18.0; keep it close to upstream so updates stay easy to merge.
#include <Arduino.h>   // needed for PlatformIO
#include <Mesh.h>

#include "DiyMesh.h"
#include "WifiLink.h"
#include "WebPanel.h"
#include "MqttLink.h"
#include "Updater.h"
#include "DiySensors.h"
#include <time.h>
#include <Preferences.h>
#include <diy_version.h>
#ifndef DIY_BOARD_NAME
  #define DIY_BOARD_NAME "DIY board"   // set per board in variants/<board>/platformio.ini
#endif   // generated by diy/scripts/version.py

#ifdef DISPLAY_CLASS
  #include "DiyUITask.h"
  static DiyUITask ui_task(board, display);
#endif

StdRNG fast_rng;
SimpleMeshTables tables;

DiyMesh the_mesh(board, radio_driver, *new ArduinoMillis(), fast_rng, rtc_clock, tables);

static WifiLink wifi_link;
static WebPanel web_panel;
static MqttLink mqtt_link;
static Updater updater;

// NTP over Wi-Fi keeps the repeater clock right (packet log times, adverts).
// The clock is only ever moved forward: MeshCore rejects packets whose timestamps
// go backwards, so a backward jump could break logins from the app.
static void ntp_sync() {
  static bool configured = false;
  static uint32_t last_check = 0;
  if (!wifi_link.isConnected()) return;
  if (!configured) {
    configTime(0, 0, "pool.ntp.org", "time.google.com");
    configured = true;
    last_check = millis() - 50000;   // first check ~10 s after start
    return;
  }
  if (millis() - last_check < 60000) return;
  last_check = millis();
  time_t now = time(nullptr);
  if (now < 1700000000) return;      // not synced yet
  uint32_t rtc = rtc_clock.getCurrentTime();
  if ((uint32_t)now > rtc + 5) {
    rtc_clock.setCurrentTime((uint32_t)now);
    Serial.printf("NTP: clock set to %lu\n", (unsigned long)now);
  }
}

void halt() {
  while (1) ;
}

static char command[160];

// One entry point for every CLI source (USB serial and web console).
// Commands that arrive over LoRa go straight to MyMesh, so the wifi.* commands
// (which hold the Wi-Fi password) are reachable only locally.
static void run_command(char* cmd, char* reply, size_t reply_len) {
  reply[0] = 0;
  if (strcmp(cmd, "diy") == 0) {
    snprintf(reply, reply_len, "%s, DIY %s [%s] (%s), MeshCore %s", DIY_BOARD_NAME, DIY_VERSION, DIY_CHANNEL, DIY_BUILD_DATE, FIRMWARE_VERSION);
    return;
  }
  if (strcmp(cmd, "sensors") == 0) {   // I2C sensors found at boot and their values
    DiySensorValue v[16];
    int n = diyReadSensors(v, 16);
    if (n <= 0) { snprintf(reply, reply_len, "sensors: none found on I2C"); return; }
    size_t o = snprintf(reply, reply_len, "sensors:");
    for (int i = 0; i < n && o < reply_len - 24; i++)
      o += snprintf(reply + o, reply_len - o, " %s=%.2f%s", v[i].key, v[i].value, v[i].unit ? v[i].unit : "");
    return;
  }
  if (wifi_link.handleCommand(cmd, reply, reply_len)) return;
  if (mqtt_link.handleCommand(cmd, reply, reply_len)) return;
  if (updater.handleCommand(cmd, reply, reply_len)) return;
  if (the_mesh.handleWatchCommand(cmd, reply, reply_len)) return;
  if (the_mesh.handleHomeCommand(cmd, reply, reply_len)) {
    if (strncmp(cmd, "home channel", 12) == 0) mqtt_link.requestDiscovery();   // add / remove the chat entities in HA
    return;
  }
  the_mesh.handleCommand(0, cmd, reply);  // NOTE: there is no sender_timestamp locally
}

// For power saving
unsigned long POWERSAVING_FIRSTSLEEP_SECS = 120; // The first sleep (if enabled) from boot

void setup() {
  Serial.begin(115200);
  Updater::earlyBoot();   // a fresh update that keeps crashing goes back to the previous slot here
  delay(1000);

  board.begin();

#ifdef DISPLAY_CLASS
  if (display.begin()) {
    display.startFrame();
    display.setCursor(0, 0);
    display.print("Please wait...");
    display.endFrame();
  }
#endif

  if (!radio_init()) {
    MESH_DEBUG_PRINTLN("Radio init failed!");
    halt();
  }

  fast_rng.begin(radio_driver.getRngSeed());

  SPIFFS.begin(true);
  FILESYSTEM* fs = &SPIFFS;
  IdentityStore store(SPIFFS, "/identity");
  if (!store.load("_main", the_mesh.self_id)) {
    MESH_DEBUG_PRINTLN("Generating new keypair");
    the_mesh.self_id = radio_new_identity();   // create new random identity
    int count = 0;
    while (count < 10 && (the_mesh.self_id.pub_key[0] == 0x00 || the_mesh.self_id.pub_key[0] == 0xFF)) {  // reserved id hashes
      the_mesh.self_id = radio_new_identity(); count++;
    }
    store.save("_main", the_mesh.self_id);
  }

  Serial.print("Repeater ID: ");
  mesh::Utils::printHex(Serial, the_mesh.self_id.pub_key, PUB_KEY_SIZE); Serial.println();
  Serial.printf("%s, DIY %s [%s] (%s), MeshCore %s\n", DIY_BOARD_NAME, DIY_VERSION, DIY_CHANNEL, DIY_BUILD_DATE, FIRMWARE_VERSION);

  command[0] = 0;

  sensors.begin();

  the_mesh.begin(fs);
  {  // create our NVS namespace on a fresh board, so the read-only opens below don't log nvs_open NOT_FOUND
    Preferences p;
    if (p.begin("diy", false)) p.end();
  }
  the_mesh.beginDiy();
  the_mesh.beginHome();

#ifdef DISPLAY_CLASS
  ui_task.begin(the_mesh.getNodePrefs(), &the_mesh, &wifi_link, DIY_VERSION, FIRMWARE_VERSION);
#endif

  {  // setup AP name suffix: first two bytes of our public key, e.g. "98BF"
    char sfx[5];
    snprintf(sfx, sizeof(sfx), "%02X%02X", the_mesh.self_id.pub_key[0], the_mesh.self_id.pub_key[1]);
    wifi_link.begin(the_mesh.getNodeName(), sfx);
  }
  mqtt_link.begin(&the_mesh, &wifi_link, the_mesh.self_id.pub_key);
  web_panel.setMqtt(&mqtt_link);
  the_mesh.setWatchHandler([](const char* key, const char* name, bool online, bool removed) {
    mqtt_link.publishWatch(key, name, online, removed);   // watched neighbour -> Home Assistant
  });
  the_mesh.setHomeChatHandler([](const char* from, const char* text, int8_t snr4, uint8_t hops) {
    mqtt_link.publishChatIn(from, text, snr4, hops);   // channel "Home" -> Home Assistant
  });
  updater.begin(&wifi_link);
  mqtt_link.setUpdater(&updater);
  setUpdaterClock([]() -> uint32_t { return rtc_clock.getCurrentTime(); });
  web_panel.setUpdater(&updater);
#ifdef DISPLAY_CLASS
  ui_task.setMqtt(&mqtt_link);
  ui_task.setUpdater(&updater);
#endif
  web_panel.begin(&the_mesh, &wifi_link, run_command);

  // send out initial zero hop Advertisement to the mesh
#if ENABLE_ADVERT_ON_BOOT == 1
  the_mesh.sendSelfAdvertisement(16000, false);
#endif

  board.onBootComplete();
}

void loop() {
  // Handle Serial CLI
  int len = strlen(command);
  if (len >= (int)sizeof(command)) {
    command[0] = 0;
    len = 0;
  }
  while (Serial.available() && len < sizeof(command)-1) {
    char c = Serial.read();
    // terminals differ: Enter may send CR, CR+LF or only LF; Backspace may send 0x08 or 0x7F
    if (c == '\n') {
      if (len == 0) continue;   // the LF of CR+LF (line already handled) or an empty line
      c = '\r';                 // LF-only terminals: LF ends the line
    }
    if (c == 0x08 || c == 0x7F) {
      if (len > 0) { command[--len] = 0; Serial.print("\b \b"); }
      continue;
    }
    command[len++] = c;
    command[len] = 0;
    Serial.print(c);
    if (c == '\r') break;
  }
  if (len == sizeof(command)-1) {  // buffer full: treat as a completed line
    command[sizeof(command)-2] = '\r';
    command[sizeof(command)-1] = 0;
  }

  if (len > 0 && command[len - 1] == '\r') {  // received complete line
    Serial.print('\n');
    command[len - 1] = 0;  // replace newline with C string null terminator
    char reply[256];
    run_command(command, reply, sizeof(reply));
    if (reply[0]) {
      Serial.print("  -> "); Serial.println(reply);
    }
    command[0] = 0;  // reset command buffer
  }

  board.loop();   // let the board feed its watchdog, run periodic housekeeping

  the_mesh.loop();
  sensors.loop();
#ifdef DISPLAY_CLASS
  ui_task.loop();
#endif
  rtc_clock.tick();

  the_mesh.loopDiy();
  wifi_link.loop();
  mqtt_link.loop();
  updater.loop();
#ifdef DISPLAY_CLASS
  {  // show the panel address on the OLED as soon as Wi-Fi gets one
    static bool was_connected = false;
    bool c = wifi_link.isConnected();
    if (c && !was_connected) ui_task.wake();
    was_connected = c;
  }
#endif
  ntp_sync();
  web_panel.loop();

  if (the_mesh.getNodePrefs()->powersaving_enabled && !the_mesh.hasPendingWork()) {
    if (the_mesh.millisHasNowPassed(POWERSAVING_FIRSTSLEEP_SECS * 1000)) { // To check if it is time to sleep
      board.sleep(30); // Sleep. Wake up after a while or when receiving a LoRa packet
    }
  }
}
