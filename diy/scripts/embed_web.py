# PlatformIO pre-build script: gzip diy/firmware/web/index.html into a C header
# ($BUILD_DIR/diy_gen/web_index.h) that the firmware serves as the web panel.
# Deterministic output (mtime=0), rewritten only when the content changes.
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
src = os.path.join(project_dir, "diy", "firmware", "web", "index.html")
gen_dir = os.path.join(env.subst("$BUILD_DIR"), "diy_gen")  # noqa: F821
dst = os.path.join(gen_dir, "web_index.h")

with open(src, "rb") as fh:
    raw = fh.read()
gz = gzip.compress(raw, compresslevel=9, mtime=0)

lines = [
    "// Generated by diy/scripts/embed_web.py from diy/firmware/web/index.html. Do not edit.",
    "#pragma once",
    "#include <Arduino.h>",
    "static const size_t WEB_INDEX_GZ_LEN = %d;" % len(gz),
    "static const uint8_t WEB_INDEX_GZ[] PROGMEM = {",
]
for i in range(0, len(gz), 20):
    lines.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
lines.append("};")
content = "\n".join(lines) + "\n"

os.makedirs(gen_dir, exist_ok=True)
old = None
if os.path.exists(dst):
    with open(dst, "r", encoding="ascii") as fh:
        old = fh.read()
if old != content:
    with open(dst, "w", encoding="ascii", newline="\n") as fh:
        fh.write(content)
print("embed_web: index.html %d bytes -> gzip %d bytes" % (len(raw), len(gz)))

env.Append(CPPPATH=[gen_dir])  # noqa: F821
