# PlatformIO pre-build script: writes $BUILD_DIR/diy_gen/diy_version.h with
#   DIY_VERSION     - our release tag (env DIY_VERSION, set by CI on releases),
#                     otherwise `git describe --tags --always --dirty`, otherwise "dev"
#   DIY_BUILD_DATE  - UTC build date
#   DIY_CHANNEL     - "release", "beta" or "dev" (env DIY_CHANNEL from CI; "-beta"/"-rc" in the
#                     tag also means beta; local builds are "dev")
# Upstream FIRMWARE_VERSION is left untouched on purpose: MeshCore apps may read it.
import datetime
import os
import subprocess

Import("env")  # noqa: F821

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
gen_dir = os.path.join(env.subst("$BUILD_DIR"), "diy_gen")  # noqa: F821
dst = os.path.join(gen_dir, "diy_version.h")

version = os.environ.get("DIY_VERSION", "").strip()
if not version:
    try:
        version = subprocess.check_output(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=project_dir, stderr=subprocess.DEVNULL, text=True).strip()
    except Exception:
        version = ""
if not version:
    version = "dev"
version = "".join(c for c in version if c.isalnum() or c in "._-+")[:64]
channel = os.environ.get("DIY_CHANNEL", "").strip().lower()
if channel not in ("release", "beta", "dev"):
    channel = "dev"
if channel == "release" and ("-beta" in version.lower() or "-rc" in version.lower()):
    channel = "beta"
date = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")

content = (
    "// Generated by diy/scripts/version.py. Do not edit.\n"
    "#pragma once\n"
    '#define DIY_VERSION "%s"\n'
    '#define DIY_BUILD_DATE "%s"\n'
    '#define DIY_CHANNEL "%s"\n' % (version, date, channel)
)
os.makedirs(gen_dir, exist_ok=True)
old = None
if os.path.exists(dst):
    with open(dst, "r", encoding="ascii") as fh:
        old = fh.read()
if old != content:
    with open(dst, "w", encoding="ascii", newline="\n") as fh:
        fh.write(content)
print("version: DIY_VERSION=%s DIY_BUILD_DATE=%s DIY_CHANNEL=%s" % (version, date, channel))

env.Append(CPPPATH=[gen_dir])  # noqa: F821
